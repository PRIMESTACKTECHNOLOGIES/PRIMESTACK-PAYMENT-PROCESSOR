/**
 * Offline Queue Manager
 * Handles transactions queued when merchant has no internet connection.
 * When connection restores, Android app calls /api/v1/offline/sync
 * and this module processes everything through Stripe.
 *
 * Risk model: Merchant bears the loss if a card declines after sync.
 */

const crypto = require('crypto');
const database = require('./database');

class OfflineQueue {

    /**
     * Queue a transaction that was captured offline
     * Called by Android app when internet is unavailable
     */
    queueTransaction(merchantId, txnData) {
        const {
            amount,
            currency,
            cardLast4,
            cardBrand,
            cardExpiry,        // MM/YY — for risk check only, never full PAN
            terminalId,        // which POS terminal processed this
            offlineRef,        // unique ref generated by the Android app
            capturedAt,        // ISO timestamp when captured on device
            offlineToken,      // Stripe offline token if terminal supports it
            metadata = {}
        } = txnData;

        if (!amount || !cardLast4 || !offlineRef) {
            throw new Error('amount, cardLast4 and offlineRef are required');
        }

        // Check if this offlineRef was already queued (prevent duplicates on re-sync)
        const existing = this.getByOfflineRef(offlineRef);
        if (existing) {
            return { alreadyQueued: true, queueId: existing.id, status: existing.sync_status };
        }

        const queueId = 'OQ_' + crypto.randomBytes(8).toString('hex').toUpperCase();

        const stmt = database.db.prepare(`
            INSERT INTO offline_queue (
                id, merchant_id, amount, currency, card_last4, card_brand,
                card_expiry, terminal_id, offline_ref, captured_at,
                offline_token, metadata, sync_status, risk_score,
                created_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'pending', 0, CURRENT_TIMESTAMP)
        `);

        stmt.run(
            queueId,
            merchantId,
            parseFloat(amount),
            (currency || 'USD').toUpperCase(),
            cardLast4,
            cardBrand || 'card',
            cardExpiry || null,
            terminalId || null,
            offlineRef,
            capturedAt || new Date().toISOString(),
            offlineToken || null,
            JSON.stringify(metadata)
        );

        return {
            queueId,
            offlineRef,
            status: 'pending',
            message: 'Transaction queued. Will process on next sync.'
        };
    }

    /**
     * Queue multiple transactions at once (batch sync from Android app)
     */
    queueBatch(merchantId, transactions) {
        const results = [];

        for (const txn of transactions) {
            try {
                const result = this.queueTransaction(merchantId, txn);
                results.push({ ...result, success: true });
            } catch (err) {
                results.push({
                    offlineRef: txn.offlineRef,
                    success: false,
                    error: err.message
                });
            }
        }

        return {
            total: transactions.length,
            queued: results.filter(r => r.success && !r.alreadyQueued).length,
            duplicates: results.filter(r => r.alreadyQueued).length,
            failed: results.filter(r => !r.success).length,
            results
        };
    }

    /**
     * Process all pending transactions for a merchant
     * Called during sync — processes through Stripe one by one
     */
    async processPendingForMerchant(merchantId, stripeGateway, database, auditLogger) {
        const pending = this.getPendingByMerchant(merchantId);

        if (pending.length === 0) {
            return { processed: 0, message: 'No pending transactions' };
        }

        const results = [];

        for (const item of pending) {
            const result = await this._processOfflineItem(item, stripeGateway, database, auditLogger);
            results.push(result);
        }

        return {
            total: pending.length,
            approved: results.filter(r => r.status === 'Approved').length,
            declined: results.filter(r => r.status === 'Declined').length,
            errors: results.filter(r => r.status === 'error').length,
            results
        };
    }

    /**
     * Process a single offline queue item
     * @private
     */
    async _processOfflineItem(item, stripeGateway, db, auditLogger) {
        try {
            // Mark as processing
            this._updateStatus(item.id, 'processing');

            let transactionStatus = 'Declined';
            let paymentIntentId = null;
            let responseCode = '05';
            let failureReason = null;

            if (stripeGateway.isEnabled()) {
                // If we have an offline token from Stripe Terminal, use it
                if (item.offline_token) {
                    try {
                        const pi = await stripeGateway.createPaymentIntent(
                            item.amount,
                            item.currency,
                            item.merchant_id
                        );
                        paymentIntentId = pi.id;
                        transactionStatus = 'Approved';
                        responseCode = '00';
                    } catch (stripeErr) {
                        failureReason = stripeErr.message;
                        transactionStatus = 'Declined';
                        responseCode = '05';
                    }
                } else {
                    // No offline token — record as approved (merchant takes risk)
                    // This is the standard offline POS model
                    // Real processors do this: approve offline, reverse later if fraud found
                    transactionStatus = 'Approved';
                    responseCode = '00';
                    paymentIntentId = `OFFLINE_${item.id}`;
                }
            } else {
                // Mock mode — approve everything offline
                transactionStatus = 'Approved';
                responseCode = '00';
                paymentIntentId = `OFFLINE_MOCK_${item.id}`;
            }

            // Save to main transactions table
            const txnData = {
                id: `TXN_OFFLINE_${crypto.randomUUID()}_${item.id}`,
                cardType: item.card_brand || 'Card',
                lastFour: item.card_last4,
                amount: item.amount,
                currency: item.currency,
                status: transactionStatus,
                responseCode,
                settlementStatus: transactionStatus === 'Approved' ? 'Settled' : 'N/A',
                merchantAccount: item.merchant_id,
                paymentIntentId,
                gatewayProvider: stripeGateway.isEnabled() ? 'stripe_offline' : 'mock_offline',
                processingTimeMs: 0,
                gpuProcessed: false,
                mfaVerified: false,
                encrypted: true,
                securityFlags: { cardMasked: true, encrypted: true, auditLogged: true, gpuProcessed: false }
            };

            const savedTxn = db.insertTransaction(txnData);

            // Mark queue item as synced
            this._updateStatus(item.id, 'synced', savedTxn.id, failureReason);

            auditLogger.logSecurityEvent({
                type: 'offline_transaction_synced',
                description: `Offline txn ${item.offline_ref} synced → ${transactionStatus}`,
                severity: transactionStatus === 'Approved' ? 'info' : 'warning',
                ip: 'sync',
                metadata: {
                    queueId: item.id,
                    offlineRef: item.offline_ref,
                    merchantId: item.merchant_id,
                    transactionId: savedTxn.id,
                    amount: item.amount,
                    currency: item.currency,
                    capturedAt: item.captured_at
                }
            });

            return {
                queueId: item.id,
                offlineRef: item.offline_ref,
                transactionId: savedTxn.id,
                status: transactionStatus,
                amount: item.amount,
                currency: item.currency
            };

        } catch (err) {
            this._updateStatus(item.id, 'failed', null, err.message);

            return {
                queueId: item.id,
                offlineRef: item.offline_ref,
                status: 'error',
                error: err.message
            };
        }
    }

    /**
     * Get all pending items for a merchant
     */
    getPendingByMerchant(merchantId) {
        const stmt = database.db.prepare(`
            SELECT * FROM offline_queue 
            WHERE merchant_id = ? AND sync_status = 'pending'
            ORDER BY captured_at ASC
        `);
        return stmt.all(merchantId);
    }

    /**
     * Get queue item by offline reference
     */
    getByOfflineRef(offlineRef) {
        const stmt = database.db.prepare('SELECT * FROM offline_queue WHERE offline_ref = ?');
        return stmt.get(offlineRef);
    }

    /**
     * Get full queue history for a merchant
     */
    getQueueHistory(merchantId, filters = {}) {
        let query = 'SELECT * FROM offline_queue WHERE merchant_id = ?';
        const params = [merchantId];

        if (filters.status) {
            query += ' AND sync_status = ?';
            params.push(filters.status);
        }

        query += ' ORDER BY created_at DESC';

        if (filters.limit) {
            query += ' LIMIT ?';
            params.push(filters.limit);
        }

        const stmt = database.db.prepare(query);
        return stmt.all(...params);
    }

    /**
     * Get count of pending transactions and total exposure for a merchant
     */
    getPendingExposure(merchantId) {
        const stmt = database.db.prepare(`
            SELECT 
                COUNT(*) as pending_count,
                SUM(amount) as pending_amount,
                currency
            FROM offline_queue
            WHERE merchant_id = ? AND sync_status = 'pending'
            GROUP BY currency
        `);
        return stmt.all(merchantId);
    }

    /**
     * Update queue item status
     * @private
     */
    _updateStatus(queueId, status, transactionId = null, errorMsg = null) {
        const stmt = database.db.prepare(`
            UPDATE offline_queue
            SET sync_status = ?, transaction_id = ?, error_message = ?,
                synced_at = CASE WHEN ? IN ('synced', 'failed') THEN CURRENT_TIMESTAMP ELSE NULL END,
                updated_at = CURRENT_TIMESTAMP
            WHERE id = ?
        `);
        stmt.run(status, transactionId, errorMsg, status, queueId);
    }

    /**
     * Check if a merchant has exceeded their daily offline limit
     */
    checkDailyLimit(merchantId, newAmount, dailyLimit) {
        const today = new Date().toISOString().split('T')[0];

        const stmt = database.db.prepare(`
            SELECT SUM(amount) as daily_total
            FROM offline_queue
            WHERE merchant_id = ? 
              AND DATE(captured_at) = ?
              AND sync_status IN ('pending', 'processing', 'synced')
        `);

        const result = stmt.get(merchantId, today);
        const currentTotal = result?.daily_total || 0;

        return {
            allowed: (currentTotal + newAmount) <= dailyLimit,
            currentTotal,
            newTotal: currentTotal + newAmount,
            limit: dailyLimit,
            remaining: Math.max(0, dailyLimit - currentTotal)
        };
    }
}

module.exports = new OfflineQueue();
